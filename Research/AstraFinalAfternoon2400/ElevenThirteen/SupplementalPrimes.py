@cache
def prime_extra(n):
    if n<2**64:return prime64(n)
    q=CERT.get(n)
    if not q:return False
    D=prod(q)
    return len(set(q))==len(q) and D*D>n and (n-1)%D==0 and pow(2,n-1,n)==1 and all(1<f<n and prime_extra(f) and gcd(pow(2,(n-1)//f,n)-1,n)==1 for f in q)


